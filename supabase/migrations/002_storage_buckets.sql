-- FounderAgent Storage Buckets Setup
--
-- IMPORTANT: SQL cannot create Supabase Storage buckets directly.
-- Run the following command to create buckets via the Storage API:
--
--   npx tsx scripts/setup-storage-bucket.ts
--
-- This script requires SUPABASE_SERVICE_ROLE_KEY in .env.local
--
-- After bucket creation, configure Storage RLS policies in the
-- Supabase Dashboard (Storage > Policies) or via a policy migration.
--
-- Recommended policy rules for "financial_uploads":
--   - INSERT: authenticated users can upload to paths starting with
--     their company ID (verified via company_members lookup).
--   - SELECT: authenticated users can read files within their
--     company ID prefix.
--   - DELETE: only owners/admins can delete files for their company.
--
-- Bucket: financial_uploads
--   - Purpose: Bank statements, CSVs, PDFs, spreadsheets
--   - Public: false
--   - File size limit: 10 MB
--   - Allowed MIME types: text/csv, application/pdf, application/vnd.openxmlformats-officedocument.spreadsheetml.sheet, application/vnd.ms-excel
--   - Path format: {company_id}/{upload_session_id}/{filename}
--
-- Bucket: generated_reports
--   - Purpose: PDF/Excel reports generated by the app
--   - Public: false
--   - File size limit: 50 MB
--   - Allowed MIME types: application/pdf, application/vnd.openxmlformats-officedocument.spreadsheetml.sheet
--
-- Bucket: brand_assets
--   - Purpose: Company logos, user avatars
--   - Public: true (for logo display without signed URLs)
--   - File size limit: 5 MB
--   - Allowed MIME types: image/png, image/jpeg, image/webp, image/svg+xml
